/**
 * Cosine similarity of two embeddings. Shared so the memory recall eval and
 * the API score memory the same way (ADR-0001). Mismatched lengths compare
 * the common prefix; an all-zero vector scores 0.
 */
export function cosineSimilarity(a: Float32Array, b: Float32Array): number {
  let dot = 0;
  let na = 0;
  let nb = 0;
  for (let i = 0; i < a.length && i < b.length; i++) {
    const x = a[i] ?? 0;
    const y = b[i] ?? 0;
    dot += x * y;
    na += x * x;
    nb += y * y;
  }
  return na === 0 || nb === 0 ? 0 : dot / Math.sqrt(na * nb);
}
